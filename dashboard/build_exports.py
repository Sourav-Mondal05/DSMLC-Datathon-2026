"""Build PRIVATE Streamlit tables from real engineered competition records.

What this file does
-------------------
1. Uses `outputs/model_features.parquet` generated by Member 1's feature script.
2. Iterates through the Parquet file in batches to avoid loading ~5M records
   into one Python dataframe. Processes *real* well-day observations only.
3. Calculates historical total produced oil, logged downtime, and the count
   of well-days flagged by the existing `possible_invisible_loss` rule.
4. Exports recent (last 120 calendar days) real well readings for investigation.
5. Creates a per-well candidate shortfall summary and a failure event history.
6. Does NOT train a model. ML risk and optimization files come from Member 2.
7. Leaves all generated datasets in `outputs/` (private, Git-ignored).
8. Writes a PRIVATE candidate for a public-safe aggregate report, but does NOT
   publish it. Sharing even derived aggregates needs team/provider review.

Needed source files:
    outputs/model_features.parquet
    data/production_failures.parquet (optional but recommended)
    outputs/well_risk_predictions.csv (produced separately by src/predict.py)
    outputs/maintenance_priorities.csv (produced by src/optimization.py)

Run from repository root:
    python dashboard/build_exports.py

The hidden-loss flag is a screening rule, NOT confirmed missing/recoverable oil.
The observations are historical daily aggregates, not real-time telemetry.
"""
from __future__ import annotations

import json
from pathlib import Path
from collections import defaultdict
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs"
DATA = ROOT / "data"
SOURCE = OUT / "model_features.parquet"
RECENT_DAYS = 120
BATCH_SIZE = 140_000

NEEDED = [
    "uwi", "production_date", "well_daily_status", "flow_direction",
    "field_operating_area", "oil_produced_m3", "water_produced_m3",
    "hours_down", "oil_baseline_7d", "oil_decline_pct",
    "possible_invisible_loss", "potential_oil_loss_m3",
    "pcp_pump_rpm", "pump_efficiency_pct", "tubing_pressure_kpa",
]


def clean_boolean(series: pd.Series) -> pd.Series:
    """Handle boolean Parquet values and string-encoded true/false consistently."""
    if pd.api.types.is_bool_dtype(series):
        return series.fillna(False).astype(bool)
    return series.astype("string").str.lower().isin(["true", "1", "yes"])


def standardize_batch(df: pd.DataFrame) -> pd.DataFrame:
    """Clean only invalid measurement values; never invent missing values."""
    x = df.copy()
    x["uwi"] = x["uwi"].astype("string").str.strip()
    x["production_date"] = pd.to_datetime(x["production_date"], errors="coerce").dt.normalize()
    x = x.dropna(subset=["uwi", "production_date"])
    x = x.loc[x["uwi"].ne("")]
    if "well_daily_status" in x:
        x = x.loc[x["well_daily_status"].astype("string").str.lower().eq("producing")]
    elif "flow_direction" in x:
        x = x.loc[x["flow_direction"].astype("string").str.lower().eq("production")]
    for c in ("oil_produced_m3", "water_produced_m3", "hours_down", "oil_baseline_7d", "oil_decline_pct", "potential_oil_loss_m3", "pcp_pump_rpm", "pump_efficiency_pct", "tubing_pressure_kpa"):
        x[c] = pd.to_numeric(x[c], errors="coerce")
    x.loc[x["oil_produced_m3"] < 0, "oil_produced_m3"] = np.nan
    x.loc[~x["hours_down"].between(0, 24), "hours_down"] = np.nan
    x.loc[(x["tubing_pressure_kpa"] < 0) | (x["tubing_pressure_kpa"] >= 999999), "tubing_pressure_kpa"] = np.nan
    x["possible_invisible_loss"] = clean_boolean(x["possible_invisible_loss"])
    x["candidate_shortfall_m3"] = x["potential_oil_loss_m3"].clip(lower=0).where(x["possible_invisible_loss"], 0).fillna(0)
    return x


def monthly_aggregate(daily: pd.DataFrame) -> list[dict]:
    """Prepare aggregate-only monthly summary without any individual well IDs."""
    if daily.empty:
        return []
    df = daily.copy()
    df["month"] = pd.to_datetime(df["production_date"]).dt.to_period("M").astype(str)
    monthly = df.groupby("month", as_index=False).agg(
        oil_m3=("oil_m3", "sum"),
        candidate_days=("candidate_days", "sum"),
        candidate_shortfall_m3=("candidate_shortfall_m3", "sum"),
    )
    return [
        {"month": r.month, "oil_m3": round(float(r.oil_m3), 1),
         "candidate_days": int(r.candidate_days),
         "candidate_shortfall_m3": round(float(r.candidate_shortfall_m3), 1)}
        for r in monthly.itertuples(index=False)
    ]


def main():
    try:
        import pyarrow.parquet as pq
    except ImportError as exc:
        raise SystemExit("Missing pyarrow. Run: python -m pip install -r dashboard/requirements.txt") from exc
    if not SOURCE.is_file():
        raise SystemExit("Missing outputs/model_features.parquet. Run src/data_cleaning.py and src/feature_engineering.py first.")
    OUT.mkdir(parents=True, exist_ok=True)
    file = pq.ParquetFile(SOURCE)
    available = set(file.schema.names)
    needed = [c for c in NEEDED if c in available]
    required = {"uwi", "production_date", "oil_produced_m3", "possible_invisible_loss", "potential_oil_loss_m3", "oil_baseline_7d"}
    absent = sorted(required - available)
    if absent:
        raise SystemExit(f"Required engineered columns missing: {absent}")
    # Pre-extract newest observation date and IDs from lightweight columns only.
    newest = pd.Timestamp("1900-01-01")
    all_ids = set()
    for batch in file.iter_batches(columns=["uwi", "production_date"], batch_size=BATCH_SIZE):
        ids = batch.column("uwi").to_pylist()
        all_ids.update(v.strip() for v in ids if isinstance(v, str) and v.strip())
        dates = pd.to_datetime(batch.column("production_date").to_pandas(), errors="coerce")
        if dates.notna().any():
            newest = max(newest, dates.max().normalize())
    cutoff = newest - pd.Timedelta(days=RECENT_DAYS - 1)
    print("Found", len(all_ids), "distinct well IDs; newest date", newest.date(), flush=True)

    daily_parts, candidate_parts, area_parts, recent_parts = [], [], [], []
    producing_ids = set()
    for batch_number, batch in enumerate(file.iter_batches(columns=needed, batch_size=BATCH_SIZE), 1):
        raw = batch.to_pandas()
        for col in NEEDED:
            if col not in raw:
                raw[col] = np.nan
        df = standardize_batch(raw)
        if df.empty:
            continue
        producing_ids.update(df["uwi"].dropna().astype(str).tolist())
        # Grouping within batches is combined across all batches below.
        daily_parts.append(df.groupby("production_date", as_index=False).agg(
            oil_m3=("oil_produced_m3", "sum"),
            down_hours=("hours_down", "sum"),
            candidate_days=("possible_invisible_loss", "sum"),
            candidate_shortfall_m3=("candidate_shortfall_m3", "sum"),
        ))
        cand = df.loc[df["possible_invisible_loss"], ["uwi", "field_operating_area", "production_date", "candidate_shortfall_m3"]]
        if not cand.empty:
            candidate_parts.append(cand.groupby("uwi", as_index=False).agg(
                candidate_days=("production_date", "size"),
                estimated_shortfall_m3=("candidate_shortfall_m3", "sum"),
                last_candidate_date=("production_date", "max"),
            ))
        area_parts.append(df[["uwi", "field_operating_area"]].dropna(subset=["uwi"]).drop_duplicates("uwi"))
        recent = df[df["production_date"].ge(cutoff)].copy()
        if not recent.empty:
            recent_parts.append(recent[[
                "uwi", "production_date", "oil_produced_m3", "oil_baseline_7d", "oil_decline_pct",
                "hours_down", "pcp_pump_rpm", "pump_efficiency_pct", "tubing_pressure_kpa",
                "possible_invisible_loss", "candidate_shortfall_m3",
            ]])
        if batch_number % 10 == 0:
            print("Processed", batch_number, "batches", flush=True)

    daily = pd.concat(daily_parts).groupby("production_date", as_index=False).agg(
        oil_m3=("oil_m3", "sum"), down_hours=("down_hours", "sum"),
        candidate_days=("candidate_days", "sum"),
        candidate_shortfall_m3=("candidate_shortfall_m3", "sum"),
    ).sort_values("production_date")
    daily.to_csv(OUT / "dashboard_daily.csv", index=False)

    if candidate_parts:
        candidates = pd.concat(candidate_parts).groupby("uwi", as_index=False).agg(
            candidate_days=("candidate_days", "sum"),
            estimated_shortfall_m3=("estimated_shortfall_m3", "sum"),
            last_candidate_date=("last_candidate_date", "max"),
        ).sort_values("estimated_shortfall_m3", ascending=False)
    else:
        candidates = pd.DataFrame(columns=["uwi", "candidate_days", "estimated_shortfall_m3", "last_candidate_date"])
    candidates.to_csv(OUT / "dashboard_loss_candidates.csv", index=False)
    areas = pd.concat(area_parts).drop_duplicates("uwi", keep="last")
    areas.to_csv(OUT / "dashboard_well_areas.csv", index=False)
    recent = pd.concat(recent_parts).sort_values(["uwi", "production_date"]).drop_duplicates(["uwi", "production_date"], keep="last") if recent_parts else pd.DataFrame(columns=["uwi", "production_date"])
    recent.to_csv(OUT / "dashboard_well_recent.csv", index=False)

    failures_path = DATA / "production_failures.parquet"
    failure_count = None
    if failures_path.is_file():
        failures = pd.read_parquet(failures_path, columns=["uwi", "failure_start_date", "failure_type", "cause"])
        failures["uwi"] = failures["uwi"].astype("string").str.strip()
        failures["failure_start_date"] = pd.to_datetime(failures["failure_start_date"], errors="coerce")
        failures = failures.dropna(subset=["uwi", "failure_start_date"])
        failures.to_csv(OUT / "dashboard_failures.csv", index=False)
        failure_count = len(failures)

    summary = {
        "source": "Original competition records; derived historical features; NOT live",
        "first_date": str(daily["production_date"].min().date()),
        "last_date": str(newest.date()),
        "all_wells": len(all_ids),
        "producing_wells_in_period": len(producing_ids),
        "candidate_wells": int(len(candidates)),
        "candidate_well_days": int(daily["candidate_days"].sum()),
        "candidate_shortfall_m3": round(float(daily["candidate_shortfall_m3"].sum()), 2),
        "recorded_failures": failure_count,
    }
    (OUT / "dashboard_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    public_candidate = {
        "label": "REVIEW REQUIRED before any public upload — historical aggregate only",
        "summary": summary,
        "monthly": monthly_aggregate(daily),
    }
    (OUT / "public_aggregate_REVIEW.json").write_text(json.dumps(public_candidate, indent=2), encoding="utf-8")
    print("Completed PRIVATE dashboard exports. No file was published.", flush=True)
    print("Full production period:", summary["first_date"], "to", summary["last_date"], flush=True)
    print("Flagged candidate well-days:", summary["candidate_well_days"], flush=True)


if __name__ == "__main__":
    main()
