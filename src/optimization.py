"""
Member 2 - Risk-based inspection priority and scenario-based impact model

1. Purpose: combine estimated failure-risk rank with each producing well's
   recent oil baseline to help an operator choose where to investigate first.
2. Input: outputs/well_risk_predictions.csv generated by src/predict.py.
   Optionally uses data/well_jobs.parquet for historical maintenance cost context.
3. Ranking: priority score = relative risk percentile x recent daily oil
   baseline. This is a HEURISTIC; it is not a validated economic optimizer.
4. Scenario: assumed downtime days x recent oil baseline gives the amount
   of production EXPOSED to one hypothetical downtime episode, not the amount
   that a maintenance intervention is proven to recover.
5. Optional value scenario: multiply volume by a user-supplied CAD/m3 price;
   price is not supplied in the hackathon dataset and is never invented.
6. Output: outputs/maintenance_priorities.csv, optionally with the number
   of historical jobs and median field cost estimate, for the Streamlit dashboard
   and the Canary teammate's risk/priority visualization.
7. Caution: every recommended action is an INSPECTION / REVIEW priority,
   not an autonomous pump setpoint or an instruction to perform maintenance.
8. Privacy: outputs retain UWI; do not commit them to a public repository.

Usage: python src/optimization.py --assumed-downtime-days 3
Optional: --oil-price-cad-per-m3 70 (hypothetical user-provided scenario)
"""
import argparse
from pathlib import Path
import numpy as np
import pandas as pd
from ml_utils import ROOT


def attach_historical_job_costs(priorities, jobs):
    """Attach retrospective job cost estimates, without claiming future savings.

    Only the UWI and field estimate are used; actual_final_job_cost is
    empty in the competition handbook. These are past estimates, not prices
    for a future repair, and should be shown with that qualification.
    """
    needed = {"uwi", "field_est_total"}
    if not needed.issubset(jobs.columns):
        raise ValueError("well_jobs data must have uwi and field_est_total")
    j = jobs[["uwi", "field_est_total"]].copy()
    j["uwi"] = j["uwi"].astype("string").str.strip()
    j["field_est_total"] = pd.to_numeric(j["field_est_total"], errors="coerce")
    j = j.loc[j["field_est_total"].ge(0) & j["uwi"].notna()]
    stats = j.groupby("uwi")["field_est_total"].agg(
        historical_job_count="size", historical_median_job_estimate="median"
    ).reset_index()
    return priorities.merge(stats, on="uwi", how="left", validate="one_to_one")


def prioritize(data, downtime_days=3.0, price_cad_per_m3=None):
    """Return transparent priority rankings from model scores and oil baseline."""
    df = data.copy()
    needed = ["uwi", "as_of_date", "risk_score", "oil_baseline_7d"]
    missing = [c for c in needed if c not in df.columns]
    if missing:
        raise ValueError(f"Missing prediction columns: {missing}")
    if downtime_days <= 0:
        raise ValueError("Assumed downtime days must be greater than zero.")
    if price_cad_per_m3 is not None and price_cad_per_m3 <= 0:
        raise ValueError("Oil price must be positive when provided.")
    df["oil_baseline_7d"] = pd.to_numeric(df["oil_baseline_7d"], errors="coerce")
    df["risk_score"] = pd.to_numeric(df["risk_score"], errors="coerce")
    df = df.dropna(subset=["risk_score"])
    df["daily_oil_at_risk_m3"] = df["oil_baseline_7d"].clip(lower=0).fillna(0)
    df["risk_percentile"] = df["risk_score"].rank(pct=True, method="average")
    df["priority_score"] = df["risk_percentile"] * df["daily_oil_at_risk_m3"]
    df["priority_percentile"] = df["priority_score"].rank(pct=True, method="average")
    df["priority"] = np.select(
        [df["priority_percentile"] >= 0.90, df["priority_percentile"] >= 0.70],
        ["High", "Medium"], default="Low"
    )
    df["assumed_downtime_days"] = downtime_days
    df["hypothetical_exposed_oil_m3"] = df["daily_oil_at_risk_m3"] * downtime_days
    if price_cad_per_m3 is not None:
        df["assumed_oil_price_cad_per_m3"] = price_cad_per_m3
        df["hypothetical_exposed_value_cad"] = (
            df["hypothetical_exposed_oil_m3"] * price_cad_per_m3
        )
    df["recommended_action"] = np.select(
        [df["priority"] == "High", df["priority"] == "Medium"],
        ["Review recent pump and production trends promptly",
         "Schedule an operator review"],
        default="Continue routine monitoring"
    )
    return df.sort_values("priority_score", ascending=False)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", default=str(ROOT / "outputs" / "well_risk_predictions.csv"))
    parser.add_argument("--assumed-downtime-days", type=float, default=3.0)
    parser.add_argument("--jobs", default=str(ROOT / "data" / "well_jobs.parquet"))
    parser.add_argument("--oil-price-cad-per-m3", type=float, default=None)
    args = parser.parse_args()
    df = prioritize(pd.read_csv(args.input), args.assumed_downtime_days,
                    args.oil_price_cad_per_m3)
    if Path(args.jobs).exists():
        jobs = pd.read_parquet(args.jobs, columns=["uwi", "field_est_total"])
        df = attach_historical_job_costs(df, jobs)
        print("Included historical job cost estimates from well_jobs.parquet")
    else:
        print("Optional well_jobs.parquet not found; skipping historical job cost context")
    output = ROOT / "outputs" / "maintenance_priorities.csv"
    output.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output, index=False)
    print(f"Saved {len(df):,} well recommendations to: {output}")
    print("Warning: exposure is a hypothetical scenario, not proven savings.")


if __name__ == "__main__":
    main()
